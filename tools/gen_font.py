# Code page 437 positions for the line-drawing and shade cells text screens commonly use.
# Each is drawn from four arms (up, down, left, right) of 0 none, 1 single, 2 double.
BOXES = {
    0xB3: (1, 1, 0, 0), 0xB4: (1, 1, 1, 0), 0xBF: (0, 1, 1, 0), 0xC0: (1, 0, 0, 1),
    0xC1: (1, 0, 1, 1), 0xC2: (0, 1, 1, 1), 0xC3: (1, 1, 0, 1), 0xC4: (0, 0, 1, 1),
    0xC5: (1, 1, 1, 1), 0xD9: (1, 0, 1, 0), 0xDA: (0, 1, 0, 1),
    0xBA: (2, 2, 0, 0), 0xBB: (0, 2, 2, 0), 0xBC: (2, 0, 2, 0), 0xC8: (2, 0, 0, 2),
    0xC9: (0, 2, 0, 2), 0xCD: (0, 0, 2, 2), 0xB9: (2, 2, 2, 0), 0xCC: (2, 2, 0, 2),
    0xCA: (2, 0, 2, 2), 0xCB: (0, 2, 2, 2), 0xCE: (2, 2, 2, 2),
}
SHADES = {0xB0: (0x88, 0x22), 0xB1: (0xAA, 0x55), 0xB2: (0xEE, 0xBB), 0xDB: (0xFF, 0xFF)}


def parse(art):
    rows = art.split()
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), art
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]


def box(up, down, left, right, height):
    """Arms meet at the cell centre; double arms are two lines one pixel either side."""
    mid = height // 2
    rows = [0] * height
    vert = {1: 0x18, 2: 0x24}
    for y in range(height):
        if (y < mid and up) or (y > mid and down) or (y == mid and (up or down)):
            rows[y] |= vert[max(up, down)]
    for arm, mask in ((left, 0xF0), (right, 0x0F)):
        if arm == 1:
            rows[mid] |= mask
        elif arm == 2:
            rows[mid - 1] |= mask
            rows[mid + 1] |= mask
    return rows


def table(height):
    out = []
    for code in range(256):
        ch = chr(code)
        if ch in GLYPHS:
            rows = parse(GLYPHS[ch])
            rows = [r for r in rows for _ in range(height // 8)]
        elif code in BOXES:
            rows = box(*BOXES[code], height)
        elif code in SHADES:
            a, b = SHADES[code]
            rows = [a if y % 2 == 0 else b for y in range(height)]
        else:
            rows = [0] * height
        out.append(rows)
    return out


def emit(name, height):
    lines = [f"const uint8_t {name}[256][{height}] = {{"]
    for code, rows in enumerate(table(height)):
        lines.append("    {" + ", ".join(f"0x{r:02X}" for r in rows) + f"}}, /* {code:02X} */")
    lines.append("};")
    return "\n".join(lines)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "runtime/src/font.c"
    text = ("/* Generated by tools/gen_font.py: the BIOS ROM font (original design). */\n"
            "#include \"font.h\"\n\n" + emit("font_8x8", 8) + "\n\n" + emit("font_8x16", 16) + "\n")
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
